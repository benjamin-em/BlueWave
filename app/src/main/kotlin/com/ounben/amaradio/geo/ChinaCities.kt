    /**
     * Nearest city to a coarse fix. Returns null if the fix is far outside China
     * (beyond ~800km of the nearest city) — in that case the caller should
     * fall back to the system-locale country rather than guessing.
     */
    fun nearestCity(lat: Double, lon: Double): City? {
        var best: City? = null
        var bestDist = Double.MAX_VALUE
        cities.forEach { c ->
            val d = haversineKm(lat, lon, c.lat, c.lon)
            if (d < bestDist) { bestDist = d; best = c }
        }
        return if (bestDist < 800.0) best else null
    }

    private fun haversineKm(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val r = 6371.0
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val a = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
            Math.cos(Math.toRadians(lat1)) * Math.cos(Math.toRadians(lat2)) *
            Math.sin(dLon / 2) * Math.sin(dLon / 2)
        return r * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
    }
